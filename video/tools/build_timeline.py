"""Build the scene timeline from the voice-over timings.

Reads audio/vo/timing.json (written by synth.py) and writes src/timeline.js,
which the composition (src/index.html) and the audio mix both use, so picture
and voice stay in sync whenever the voice-over is regenerated.
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FPS = 30

# scene id, background type, VO segments (1-based), transition INTO this scene
SCENES = [
    ("s1",  "dark",  [1],          None),
    ("s2",  "light", [2, 3],       "wipe"),
    ("s3",  "tint",  [4, 5, 6, 7], "fade"),
    ("s4",  "dark",  [8],          "wipe"),
    ("s5",  "light", [9],          "fade"),
    ("s6",  "tint",  [10],         "fade"),
    ("s7",  "dark",  [11],         "wipe"),
    ("s8",  "light", [12],         "fade"),
    ("s9",  "tint",  [13],         "fade"),
    ("s10", "dark",  [14],         "wipe"),
    ("s11", "dark",  [],           "fade"),   # end card, no voice
]
LEAD = {"s1": 0.55}          # scene start -> first word
DEFAULT_LEAD = 0.6
SEG_GAP = 0.5                # pause between two VO segments inside a scene
TAIL = {"s4": 1.3, "s7": 0.9, "s10": 1.4}   # last word -> scene end
DEFAULT_TAIL = 0.65
END_CARD = 4.8


def main():
    timing = json.load(open(os.path.join(ROOT, "audio/vo/timing.json")))
    seg_info = {s["seg"]: s for s in timing["segments"]}
    t = 0.0
    scenes, segs = [], {}
    for sid, kind, seg_ids, trans in SCENES:
        start = t
        if not seg_ids:
            end = start + END_CARD
        else:
            cur = start + LEAD.get(sid, DEFAULT_LEAD)
            for k, n in enumerate(seg_ids):
                info = seg_info[n]
                segs[n] = {
                    "seg": n, "start": round(cur, 3), "end": round(cur + info["dur"], 3),
                    "phrases": [{"start": round(cur + p["start"], 3), "end": round(cur + p["end"], 3)}
                                for p in info["phrases"]],
                }
                cur += info["dur"]
                if k < len(seg_ids) - 1:
                    cur += SEG_GAP
            end = cur + TAIL.get(sid, DEFAULT_TAIL)
        scenes.append({"id": sid, "kind": kind, "start": round(start, 3), "end": round(end, 3),
                       "trans": trans, "segs": seg_ids})
        t = end
    duration = round(t, 3)
    tl = {"fps": FPS, "duration": duration, "frames": int(round(duration * FPS)),
          "scenes": scenes, "segs": [segs[k] for k in sorted(segs)]}
    out = os.path.join(ROOT, "src/timeline.js")
    with open(out, "w") as f:
        f.write("// generated by tools/build_timeline.py — do not edit\n")
        f.write("window.TL = " + json.dumps(tl, ensure_ascii=False, indent=1) + ";\n")
    json.dump(tl, open(os.path.join(ROOT, "audio/timeline.json"), "w"), indent=1)
    print(f"duration {duration}s, {tl['frames']} frames")
    for s in scenes:
        print(f"  {s['id']:4s} {s['kind']:5s} {s['start']:6.2f} -> {s['end']:6.2f}  ({s['trans']})")


if __name__ == "__main__":
    sys.exit(main())
